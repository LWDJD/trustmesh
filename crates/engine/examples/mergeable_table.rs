//! # 关键区别：A12 的稀疏表是「最终分布」，不是「可再合并的中间表示」。
//!
//! 作者的表述里有一个重要的措辞：「其他人来的数据和自己的数据**最终会合并为一个数据**，
//! 而且**合并后的大小有上限**」。
//!
//! 这可以读成两种不同的架构，代价差别很大：
//!
//! ## 读法 1（A12 现在做的）：合并 = β 合成出一条完整向量，再压成定长表
//!
//! ```text
//! 我的评分表（精确）  ─┐
//!                     ├→ β 合成 → 完整向量 → 截断到 cap → 定长稀疏表（发布出去）
//! 收到的 m 份观点     ─┘
//! ```
//!
//! * 合并发生在**发布时**，合并的输入是「我自己 + 我收到的观点」；
//! * 输出的定长表**不能再和别人的定长表合并**（它是最终结果，不含中间权重）；
//! * 所以传播是「一跳一跳重新计算」：我从 A、B 收到观点 → 算出我的 → 发布；
//!   C 从我这收到 → 算它的 → 发布。**每跳都要重算一次完整分布**。
//!
//! ## 读法 2：合并 = 定长表之间直接可合并（线性 mergeable）
//!
//! ```text
//! 我的表 ─┐
//!         ├→ merge → 一张更大的表（再截断到 cap）→ 发布
//! 收到的表 ─┘
//! ```
//!
//! * 合并发生在**数据结构层**，`merge(t1, t2)` 就是两表相加（或加权相加）；
//! * 好处：多跳传播可以**在表上累积**，不必每跳重算完整分布；
//! * 代价：**表里必须保留中间信息**（不能只是最终分数），否则合并出的东西不是「谁可信」而是垃圾。
//!
//! **这两个读法的差别不是实现细节，是架构。** 本探针把差别量化。
//!
//! 用法：cd crates/view && cargo run --release --example mergeable_table

use tm_engine::view::{CompressedView, ViewParams};

fn key(i: u32) -> [u8; 32] {
    let mut k = [0u8; 32];
    k[0] = i as u8;
    k[1] = ((i >> 8) & 0xFF) as u8;
    k
}

fn main() {
    println!("# 两种「合并」读法的代价对比");
    println!();

    let params = ViewParams::new(2048, 5, 11);

    // 造两份观点（各给不同的一组账户打分）
    let mut v1: Vec<([u8; 32], f32)> = Vec::new();
    let mut v2: Vec<([u8; 32], f32)> = Vec::new();
    for i in 0..50u32 {
        v1.push((key(i), 0.5));
    }
    for i in 50..100u32 {
        v2.push((key(i), 0.5));
    }
    let a = CompressedView::from_pairs(params, &v1);
    let b = CompressedView::from_pairs(params, &v2);

    // 现行 Count Sketch **可以**直接 merge（这是它的核心优点）
    let mut m = a.clone();
    m.merge(&b, 0.5, 0.5);
    println!("## 现行 Count Sketch：**可合并**");
    println!(
        "  a.bytes() = {}, b.bytes() = {}, merge 后 = {}",
        a.bytes(),
        b.bytes(),
        m.bytes()
    );
    let q0 = m.query(&key(0));
    let q50 = m.query(&key(50));
    println!(
        "  merge 后查 key(0) = {:.4}，key(50) = {:.4}（两边的信息都在）",
        q0, q50
    );
    println!("  → 定长 40960 字节，合并**不增大体积**（这是 sketch 的定义性质）");
    println!();

    println!("## 但 Count Sketch 的合并有一个致命限制");
    println!("  它合并的是**读数**，不是**权重结构**。也就是说：");
    println!("  merge 之后你无法回答「这个读数是从谁的份额里来的」——信息已经丢了。");
    println!("  而反女巫需要的恰恰是**权重结构**（份额 × 衰减 × 惩罚）。");
    println!();

    println!("## A12 定长稀疏表（对照）");
    println!("  cap×6+2 字节；表里存的是**最终归一化分数**（Σ ≡ 1）");
    println!("  它是「一条完整观点的压缩」，**不是**「可以互相叠加的中间态」");
    println!("  merge(表1, 表2) 语义不明：两张表的 Σ 各为 1，加起来 Σ = 2，不再合法");
    println!();

    println!("## 结论：作者的表述更接近哪个？");
    println!();
    println!("作者原话：「其他人来的数据和自己的数据最终会合并为一个数据，");
    println!("而且合并后的大小有上限，这个数据就是最终用来对任意账户检查分数的数据」");
    println!();
    println!("→ 关键词「**最终用来检查分数**」说明这是**读法 1**（最终分布，不是中间态）；");
    println!("→ 关键词「**合并后的大小有上限**」在 A12 里就是 `cap`（截断到 cap 条）。");
    println!();
    println!("**所以 A12 的设计正是作者要的**，不需要改成 mergeable sketch。");
    println!("唯一需要作者定的是：cap 是**全网统一**还是**每节点自定**（后者需要自描述字节头）。");
}
