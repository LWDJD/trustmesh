/// **本文件存在的唯一理由**：黄金字节必须仍能被当前代码解码。
///
/// 一旦这条红了，先读文件头「为什么需要这个测试」那一节再动手。
#[test]
fn v2_golden_snapshot_is_still_decodable() {
    let snap = EngineSnapshot::decode(GOLDEN_BYTES)
        .expect("黄金快照解不开：要么 SNAPSHOT_VERSION 被抬了，要么编码布局被改了");

    assert_eq!(
        snap.version, GOLDEN_VERSION,
        "解码出来的版本号与黄金字节里写的不一致"
    );
    assert_eq!(
        GOLDEN_BYTES.len(),
        GOLDEN_LEN,
        "黄金字节长度变了（长度本身也是格式的一部分）"
    );
}

/// `version_of` 也必须认得这段字节——它是不解码就窥版本号的快速路径。
#[test]
fn golden_bytes_version_is_visible_without_full_decode() {
    assert_eq!(
        EngineSnapshot::version_of(GOLDEN_BYTES),
        Some(GOLDEN_VERSION),
        "version_of 认不出黄金字节的版本号"
    );
}

/// 当前常量必须与黄金字节记录的版本一致。
///
/// **这条是「抬版本号时的主要报警器」**：如果有人把 `SNAPSHOT_VERSION` 抬到 3
/// 却没重新生成 golden，这条会立刻红。
#[test]
fn snapshot_version_constant_matches_golden() {
    assert_eq!(
        SNAPSHOT_VERSION, GOLDEN_VERSION,
        "SNAPSHOT_VERSION 被改了（{} → {}），但黄金快照还是 v{} 生成的。\
         如果这是有意的破坏性变更，请重新跑 gen_golden_snapshot 并更新版本历史；\
         如果是意外的，改回去。",
        GOLDEN_VERSION, SNAPSHOT_VERSION, GOLDEN_VERSION
    );
}

/// 解码后重建引擎，读数必须与生成时一致。
///
/// 这条比「能解码」更强：它锁住的是**字段语义**，不只是字节布局。
/// 如果将来有人改了某个字段的含义（比如 `total_mass` 从「接收方估计」
/// 改成「发布方声明」），这条会红——那正是 P0 那种改动应有的效果。
#[test]
fn golden_snapshot_restores_to_identical_readings() {
    let snap = EngineSnapshot::decode(GOLDEN_BYTES).expect("黄金快照解不开");

    let cfg = EngineConfig {
        view_params: ViewParams::new(64, 3, 7),
        max_views: 16,
        ..EngineConfig::default()
    };
    let e = Engine::restore(cfg, snap).expect("恢复失败：配置与快照不匹配？");

    assert_eq!(e.account_count(), 4, "账户数不对");
    assert_eq!(e.positive_count(), 3, "正分清单条数不对");
    assert_eq!(
        e.query(1, 10).to_bits(),
        0x3ed7b884,
        "query(bob) 的 f32 位模式变了（字段语义可能被改了）"
    );
    assert_eq!(
        e.query(2, 10).to_bits(),
        0x3ea7c868,
        "query(carol) 的 f32 位模式变了"
    );
}
